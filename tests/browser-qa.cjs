const assert=require("node:assert/strict");
const puppeteer=require(process.env.NITEACADEMY_PUPPETEER_PATH || "puppeteer");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const base="http://127.0.0.1:8767";
const chrome=process.env.NITEACADEMY_CHROME || (process.platform==="win32"?"C:/Program Files/Google/Chrome/Application/chrome.exe":"/usr/bin/google-chrome");
const answer="The known input is the Raleigh city, but the requested date is missing. Draft a response email that does not confirm a booking or availability. Before sending, a human must review and check the output. Request the missing date and verify the service area, and do not invent a supplier.";
async function run(){
 const errors=[];
 const browser=await puppeteer.launch({executablePath:chrome,headless:true,args:["--no-sandbox","--disable-gpu"]});
 try{
  const page=await browser.newPage();
  await page.setViewport({width:1440,height:920,deviceScaleFactor:1});
  page.on("pageerror",error=>errors.push(error.message));
  let response=await page.goto(base+"/studio/",{waitUntil:"networkidle0",timeout:30000});
  assert.ok([200,304].includes(response.status()),"HTTP "+response.status());
  await page.waitForSelector(".course-card");
  assert.equal(await page.$$eval(".course-card",x=>x.length),6);
  assert.equal(await page.$eval("#metric-done",x=>x.textContent.replace(/\s/g,"")),"0/18");
  console.log("PASS studio loads six tracks and initial zero real progress");
  const preset=await page.$eval("#goal",x=>x.value);
  assert.equal(preset,"remote");
  await page.select("#goal","ai");
  await page.click("#path-form button[type=submit]");
  assert.equal(await page.$$eval("#plan-items .plan-item",x=>x.length),3);
  assert.match(await page.$eval("#plan-items",x=>x.textContent),/AI Operator/);
  console.log("PASS learner plan is generated from selected goal");
  await page.click('button[data-open-track="ai"]');
  await page.waitForSelector('[data-track-detail="ai"]');
  assert.equal(await page.$$eval(".lesson-pick",x=>x.length),3);
  await page.click('button[data-lesson="ai:spec"]');
  assert.equal(await page.$eval("#lesson",x=>x.hidden),false);
  assert.match(await page.$eval("#lesson-title",x=>x.textContent),/Write the operator spec/);
  await page.type("#practice-draft",answer,{delay:0});
  await page.click("#evaluate-draft");
  assert.match(await page.$eval("#practice-feedback",x=>x.textContent),/100\/100/);
  assert.equal(await page.$eval("#complete-lesson",x=>x.disabled),false);
  await page.click("#complete-lesson");
  assert.match(await page.$eval("#metric-done",x=>x.textContent),/1\/18/);
  console.log("PASS practice rubric accepts a complete answer, records score once and updates portfolio");
  await page.reload({waitUntil:"networkidle0"});
  assert.match(await page.$eval("#metric-done",x=>x.textContent),/1\/18/);
  assert.equal(await page.$eval("#goal",x=>x.value),"ai");
  assert.equal(await page.$$eval(".completed-list>div",x=>x.length),1);
  console.log("PASS reload retains learning plan and progress on local device");
  await page.type("#coach-question","How do I verify a paying buyer before offering a remote task?");
  await page.click("#coach-respond");
  assert.match(await page.$eval("#coach-response",x=>x.textContent),/STRUCTURED PRACTICE COACH/);
  await page.select("#coach-mode","local");
  assert.equal(await page.$eval("#load-model",x=>x.hidden),false);
  assert.equal(await page.$eval("#coach-respond",x=>x.disabled),true);
  console.log("PASS clearly labeled free coach and opt-in model download without accidental cloud calls");
  assert.equal(await page.$$eval("#arena-lesson option",x=>x.length),18);
  await page.select("#arena-provider","claude");
  assert.match(await page.$eval("#arena-open",x=>x.href),/claude\.ai/);
  assert.match(await page.$eval("#arena-packet",x=>x.value),/fictional/i);
  await page.type("#arena-answer",answer,{delay:0});
  await page.click("#arena-score");
  assert.match(await page.$eval("#arena-feedback",x=>x.textContent),/100\/100/);
  assert.equal(await page.$$eval(".arena-entry",x=>x.length),1);
  await page.reload({waitUntil:"networkidle0"});
  assert.equal(await page.$$eval(".arena-entry",x=>x.length),1);
  assert.match(await page.$eval(".arena-entry",x=>x.textContent),/Claude/);
  console.log("PASS multi-model comparison uses manual evaluation and persists without calling a paid model API");

  await page.screenshot({path:path.join(root,"tests","studio-desktop.png"),fullPage:true});
  const horizontal=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
  assert.ok(horizontal<=2,"Desktop has horizontal overflow: "+horizontal);
  const mobile=await browser.newPage();
  await mobile.setViewport({width:390,height:844,deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on("pageerror",error=>errors.push(error.message));
  response=await mobile.goto(base+"/studio/",{waitUntil:"networkidle0"});
  assert.ok([200,304].includes(response.status()),"HTTP "+response.status());
  await mobile.waitForSelector(".course-card");
  let overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
  console.log("MOBILE_OVERFLOW_PX",overflow);if(overflow>2){console.log("OFFENDERS",await mobile.evaluate(()=>[...document.querySelectorAll("body *")].map(el=>({tag:el.tagName,cl:el.className?.toString()?.slice(0,90),right:Math.round(el.getBoundingClientRect().right),left:Math.round(el.getBoundingClientRect().left)})).filter(x=>x.right>window.innerWidth+3||x.left<-3).slice(0,24)));}
  assert.ok(overflow<=2,"Mobile horizontal overflow: "+overflow);
  await mobile.screenshot({path:path.join(root,"tests","studio-mobile.png"),fullPage:true});
  console.log("PASS 390px mobile viewport renders without horizontal overflow");
  const home=await browser.newPage();
  await home.setViewport({width:390,height:844,deviceScaleFactor:1,isMobile:true,hasTouch:true});
  home.on("pageerror",error=>errors.push(error.message));
  response=await home.goto(base+"/",{waitUntil:"networkidle0"});
  assert.ok([200,304].includes(response.status()),"HTTP "+response.status());
  assert.equal(await home.$$eval("#academy-form",x=>x.length),1);
  assert.equal(await home.$$eval('a[href="studio/"]',x=>x.length)>=3,true);
  overflow=await home.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
  console.log("HOME_MOBILE_OVERFLOW_PX",overflow);
  assert.ok(overflow<=2,"Home mobile horizontal overflow: "+overflow);
  await home.screenshot({path:path.join(root,"tests","homepage-mobile.png"),fullPage:true});
  console.log("PASS homepage preserves original application form and links to real Studio");
  assert.equal(errors.length,0,"Browser JavaScript errors: "+errors.join("; "));
  console.log("PASS no uncaught browser JavaScript errors");
 }finally{await browser.close();}
}
run().catch(error=>{console.error("BROWSER_QA_FAILED",error.stack||error);process.exit(1)});
